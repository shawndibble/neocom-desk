// Writes functions/src/data/srpDoctrineData.ts from public/data (functions cannot import
// public/). Run after the SDE data changes; functions/src/srpDoctrineData.test.ts fails on drift.
import { readFileSync, writeFileSync } from 'node:fs';

const read = (p) =>
  JSON.parse(readFileSync(new URL(`../public/data/${p}`, import.meta.url), 'utf8'));
const RACKS = new Set(['high', 'medium', 'low', 'rig', 'subsystem']);

const slots = read('fittingSlots.json');
const rackByType = {};
for (const id of Object.keys(slots).sort((a, b) => a - b)) {
  if (RACKS.has(slots[id])) rackByType[id] = slots[id];
}
const mutaplasmids = Object.keys(read('mutaplasmids.json').mutaplasmids)
  .sort((a, b) => a - b)
  .map((k) => {
    const m = read('mutaplasmids.json').mutaplasmids[k];
    return { result: m.result, bases: [...m.bases] };
  });

const out = `// Generated by scripts/build-srp-doctrine-data.mjs from public/data — do not hand-edit.
export const FITTING_RACKS: Readonly<Record<string, string>> = ${JSON.stringify(rackByType)};
export const MUTAPLASMID_BASES: readonly { result: number; bases: readonly number[] }[] = ${JSON.stringify(mutaplasmids)};
`;
writeFileSync(new URL('../functions/src/data/srpDoctrineData.ts', import.meta.url), out);
